export const LEAD = 0.6, GAP = 0.45, TAIL = 0.9;   // seconds: before a scene's first line, between lines, after the last

export const lineId = (scene, i) => `${scene.id}-${String(i).padStart(2, '0')}`;

/** A guess at how long a line takes to say, for a page opened before the voice files exist. */
export const guess = say => 0.6 + [...say].filter(c => c >= '가' && c <= '힣').length * 0.15 + (say.match(/[,.]/g) ?? []).length * 0.28;

/** Lays the scenes on one timeline. voice: line id -> seconds of speech (missing ones are guessed). */
export function layout(voice = {}) {
  let T = 0;
  const scenes = SCENES.map(sc => {
    let t = LEAD;
    const lines = sc.lines.map((ln, i) => {
      const id = lineId(sc, i), d = voice[id] ?? guess(ln.say), o = { id, t0: t, t1: t + d, say: ln.say, cap: ln.cap };
      t += d + GAP + (ln.hold ?? 0);          // hold: extra seconds the picture needs after the line is said
      return o;
    });
    const dur = t - GAP + TAIL, o = { id: sc.id, chapter: sc.chapter, start: T, dur, lines };
    T += dur;
    return o;
  });
  return { scenes, total: T };
}
