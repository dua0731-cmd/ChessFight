#   "C:/Program Files/Blender Foundation/Blender 5.2/5.2/python/bin/python.exe" -I textures/rcy_tint_shader.py
#
# Copies Library/PackageCache/com.unity.render-pipelines.universal@*/Shaders/Lit.shader and its forward and GBuffer
# passes to Assets/Art/PawnRushCarriageYard/Shaders as "ChessFight/RcyTintLit", the one change: the mesh's vertex colour
# (rcy_kit.surface_uvs writes a stone part's tone there, white elsewhere) multiplies the albedo. Everything else -
# inputs, keywords, shadows, depth, SSAO, Forward+, the material inspector, SRP Batcher - is URP's own Lit. Run again
# after a URP update. Never while Unity is in Play.

import glob, hashlib, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("RCY_UNITY_ROOT") or os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
SRC_ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
OUT_REL = "Assets/Art/PawnRushCarriageYard/Shaders"
NAME = "RcyTintLit"


def guid(rel):
    return hashlib.md5(("chessfight:" + rel).encode()).hexdigest()


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def meta(rel, importer):
    if not os.path.exists(os.path.join(ROOT, rel + ".meta")):
        write(rel + ".meta", "fileFormatVersion: 2\nguid: %s\n%s" % (guid(rel), importer))


def must(pattern, text, repl, count=1):
    new, n = re.subn(pattern, repl, text, count=count)
    if n != count:
        raise RuntimeError("URP changed: %r matched %d times" % (pattern, n))
    return new


def tint_pass(text, guard):
    text = text.replace(guard, guard.replace("UNIVERSAL_", "RCY_TINT_"))
    text = "// Generated by ArtSource/PawnRush/CarriageYardModels/textures/rcy_tint_shader.py from URP's own pass: the\n" \
           "// vertex colour (rcy_kit's stone tone) multiplies the albedo. Do not edit; run the script again.\n" + text
    text = must(r"(float2 texcoord\s*: TEXCOORD0;)", text, r"\1\n    half4 rcyColor     : COLOR;")
    text = must(r"(float2 uv\s*: TEXCOORD0;)", text, r"\1\n    half3 rcyTint                   : TEXCOORD11;")
    text = must(r"(output\.uv = TRANSFORM_TEX\(input\.texcoord, _BaseMap\);)", text, r"\1\n    output.rcyTint = input.rcyColor.rgb;")
    text = must(r"(InitializeStandardLitSurfaceData\(input\.uv, surfaceData\);)", text, r"\1\n    surfaceData.albedo *= input.rcyTint;")
    return text


def main():
    urp = sorted(glob.glob(os.path.join(SRC_ROOT, "Library/PackageCache/com.unity.render-pipelines.universal@*/Shaders")))
    if not urp:
        raise SystemExit("no URP package in Library/PackageCache (open the project in Unity once)")
    src = urp[-1]
    with open(os.path.join(src, "Lit.shader"), encoding="utf-8") as f:
        shader = f.read()
    with open(os.path.join(src, "LitForwardPass.hlsl"), encoding="utf-8") as f:
        fwd = f.read()
    with open(os.path.join(src, "LitGBufferPass.hlsl"), encoding="utf-8") as f:
        gbuf = f.read()
    shader = must(r'^Shader "Universal Render Pipeline/Lit"', shader, 'Shader "ChessFight/%s"' % NAME)
    shader = must(r'#include "Packages/com\.unity\.render-pipelines\.universal/Shaders/LitForwardPass\.hlsl"', shader,
                  '#include "%sForwardPass.hlsl"' % NAME)
    shader = must(r'#include "Packages/com\.unity\.render-pipelines\.universal/Shaders/LitGBufferPass\.hlsl"', shader,
                  '#include "%sGBufferPass.hlsl"' % NAME)
    shader = "// Generated by ArtSource/PawnRush/CarriageYardModels/textures/rcy_tint_shader.py from URP's Lit.shader (%s):\n" \
             "// the carriage yard's stone, its vertex colour multiplying the albedo. Do not edit; run the script again.\n" \
             % os.path.basename(os.path.dirname(src)) + shader
    files = {
        "%s/%s.shader" % (OUT_REL, NAME): (shader, "ShaderImporter:\n  externalObjects: {}\n  defaultTextures: []\n"
                                                    "  nonModifiableTextures: []\n  userData: \n  assetBundleName: \n"
                                                    "  assetBundleVariant: \n"),
        "%s/%sForwardPass.hlsl" % (OUT_REL, NAME): (tint_pass(fwd, "UNIVERSAL_FORWARD_LIT_PASS_INCLUDED"), None),
        "%s/%sGBufferPass.hlsl" % (OUT_REL, NAME): (tint_pass(gbuf, "UNIVERSAL_LIT_GBUFFER_PASS_INCLUDED"), None),
    }
    meta(OUT_REL, "folderAsset: yes\nDefaultImporter:\n  externalObjects: {}\n  userData: \n  assetBundleName: \n"
                  "  assetBundleVariant: \n")
    for rel, (text, importer) in files.items():
        write(rel, text)
        meta(rel, importer or "ShaderIncludeImporter:\n  externalObjects: {}\n  userData: \n  assetBundleName: \n"
                              "  assetBundleVariant: \n")
        print("RCY_SHADER", rel)
    print("RCY_SHADER guid", guid("%s/%s.shader" % (OUT_REL, NAME)))


if __name__ == "__main__":
    main()
